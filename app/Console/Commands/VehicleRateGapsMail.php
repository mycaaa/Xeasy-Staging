<?php

namespace App\Console\Commands;

use App\Http\Controllers\admin\VehicleRateGapsController;
use App\Services\Reports\VehicleRateGaps;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\Mail;

/** VEH-RATE-REPORT-01: weekly mail to HR with the vehicle rates and documents to update. */
class VehicleRateGapsMail extends Command
{
    protected $signature = 'reports:vehicle-rate-gaps {--company=1} {--to= : comma separated; default config claim_rules.vehicle_rate_report_to} {--file= : also save the Excel here}';

    protected $description = 'Weekly list of active employees whose vehicle rate or vehicle value HR must update';

    public function handle(): int
    {
        $co = (int) $this->option('company');
        $rows = (new VehicleRateGaps())->rows($co);
        $rate = count(array_filter($rows, fn ($r) => $r['rate_missing']));
        $this->info("company {$co}: ".count($rows)." employees to update ({$rate} with a missing rate)");
        $name = 'Vehicle_Rates_To_Update_'.now()->format('Ymd').'.xlsx';
        $path = 'reports/'.$name;
        \Maatwebsite\Excel\Facades\Excel::store(VehicleRateGapsController::excel($rows), $path, 'local');
        if ($f = $this->option('file')) {
            copy(storage_path('app/'.$path), $f);
        }
        $to = array_filter(array_map('trim', explode(',', (string) ($this->option('to') ?: config('claim_rules.vehicle_rate_report_to', '')))));
        if (! $to) {
            $this->warn('No recipient set (VEHICLE_RATE_REPORT_TO); Excel saved to storage/app/'.$path);

            return self::SUCCESS;
        }
        $body = "Dear HR team,\n\n".count($rows)." active employees need an update in HRIMS: {$rate} have no own-vehicle rate for the vehicle they claim (their running-km claims are paid at Rs 0 until the rate is entered), the rest are on the Own Your Car policy without the vehicle value.\n\nThe list is attached.\n\nThis mail is auto generated by Xeasy.";
        Mail::raw($body, function ($m) use ($to, $path, $name) {
            $m->to($to)->subject('Xeasy: vehicle rates to update - '.now()->format('d M Y'))->attach(storage_path('app/'.$path), ['as' => $name]);
        });
        $this->info('mailed to '.implode(', ', $to));

        return self::SUCCESS;
    }
}
